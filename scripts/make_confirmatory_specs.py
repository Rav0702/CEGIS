#!/usr/bin/env python3
"""
Confirmatory-phase specs (spec_knowledge/FULL_SCALE_PLAN.md, C1) that exist only without a grammar block: the
constraints are copied verbatim from their source, the CDGP-paper LIA grammar is added (as for
spec_files/case_split/array_search4.sl), and the synth-fun parameters are renamed to the declared variables the
constraints apply the function to, so every application is the canonical one. Unused `declare-fun`s are dropped.
Writes spec_files/confirmatory/<name>.sl.

    python scripts/make_confirmatory_specs.py
"""
import os
import re

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))
DEV = os.path.normpath(os.path.join(ROOT, ".."))
CDGP = os.path.join(DEV, "CDGP", "resources", "benchmarks_phd", "cdgp", "LIA")
OUT = os.path.join(ROOT, "spec_files", "confirmatory")

SOURCES = {  # name -> source file
    "array_search3": os.path.join(CDGP, "fg_array_search_3.sl"),
    "array_sum3_15": os.path.join(CDGP, "fg_array_sum_3_15.sl"),
    "conditional_sum_hard": os.path.join(ROOT, "benchmarks", "conditional_sum", "hard.sl"),
    "clamp_value_easy": os.path.join(ROOT, "benchmarks", "clamp_value", "easy.sl"),
    "abs_value_easy": os.path.join(ROOT, "benchmarks", "abs_value", "easy.sl"),
    "sign_function_easy": os.path.join(ROOT, "benchmarks", "sign_function", "easy.sl"),
}

GRAMMAR = """    ((Start Int ({params} 0 1
                 (+ Start Start)
                 (- Start Start)
                 (ite StartBool Start Start)))
     (StartBool Bool ((and StartBool StartBool)
                      (or  StartBool StartBool)
                      (not StartBool)
                      (<=  Start Start)
                      (=   Start Start)
                      (>=  Start Start)))))"""


def strip_comments(text):
    return "\n".join(line.split(";", 1)[0].rstrip() for line in text.splitlines())


def build(name, src):
    raw = open(src, encoding="utf-8").read()
    text = strip_comments(raw)
    m = re.search(r"\(synth-fun\s+(\S+)\s+\(((?:\s*\(\s*\S+\s+Int\s*\))+)\s*\)\s*Int\s*\)", text)
    if not m:
        raise SystemExit(f"{name}: no grammar-less Int synth-fun with Int parameters in {src}")
    fname = m.group(1)
    arity = len(re.findall(r"\(\s*\S+\s+Int\s*\)", m.group(2)))
    apps = set(re.findall(r"\(" + re.escape(fname) + r"((?:\s+[A-Za-z_][A-Za-z0-9_]*){%d})\s*\)" % arity, text))
    if len(apps) != 1:
        raise SystemExit(f"{name}: expected one argument list for {fname}, found {sorted(apps)}")
    params = apps.pop().split()
    body = text[m.end():]
    used = set(re.findall(r"\((\S+)", body))
    lines = []
    for line in body.splitlines():
        d = re.match(r"\s*\(declare-fun\s+(\S+)", line)
        if d and d.group(1) not in used - {"declare-fun"}:
            continue
        lines.append(line)
    pre = text[:m.start()]
    pre = "\n".join(l for l in pre.splitlines()
                    if not (re.match(r"\s*\(declare-fun\s+(\S+)", l)
                            and re.match(r"\s*\(declare-fun\s+(\S+)", l).group(1) not in used))
    head = (f"; {name}.sl — confirmatory-phase spec (spec_knowledge/FULL_SCALE_PLAN.md).\n"
            f";\n; GENERATED by scripts/make_confirmatory_specs.py — do not edit by hand.\n"
            f"; Constraints verbatim from\n;   {os.path.relpath(src, DEV)}\n"
            f"; which has no grammar block. The CDGP-paper LIA grammar is added, the parameters are named like the\n"
            f"; declared variables, and unused declare-funs are dropped.\n\n")
    sig = f"(synth-fun {fname} ({' '.join(f'({p} Int)' for p in params)}) Int\n" + GRAMMAR.format(params=" ".join(params))
    spec = head + pre.strip() + "\n\n" + sig + "\n" + "\n".join(lines).strip() + "\n"
    spec = re.sub(r"\n{3,}", "\n\n", spec)
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, f"{name}.sl")
    open(path, "w", encoding="utf-8", newline="\n").write(spec)
    print(f"wrote {os.path.relpath(path, ROOT)}  ({fname}, params {params})")


for n, s in SOURCES.items():
    build(n, s)
