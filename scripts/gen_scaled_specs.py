#!/usr/bin/env python3
"""
Generate scaled members of three spec families, written exactly like the small originals, into
spec_files/scaled/ (and max<n>_sygus.sl into spec_files/grammar_variants/):

  max<n>_sygus    — max_n constraints with the SyGuS-COMP LIA grammar (as max7/max8_sygus.sl)
  above<n>        — f > x_i for every input (multi-answer; as spec_files/multi_answer/above4.sl)
  array_search<n> — index of k in a sorted array, one guarded constraint per region
                    (as spec_files/case_split/array_search4.sl; sortedness as nested binary `and`)

    bench/.venv/Scripts/python scripts/gen_scaled_specs.py 30 20 20
      (max n, above n, array_search n)
"""
import os
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))
GRAMMAR_BOOL = """     (StartBool Bool ((and StartBool StartBool)
                      (or  StartBool StartBool)
                      (not StartBool)
                      (<=  Start Start)
                      (=   Start Start)
                      (>=  Start Start)))))"""


def header(name, params):
    sig = " ".join(f"({p} Int)" for p in params)
    return (f"(set-logic LIA)\n\n(synth-fun {name} ( {sig} ) Int\n"
            f"    ((Start Int ({' '.join(params)} 0 1\n"
            f"                 (+ Start Start)\n                 (- Start Start)\n"
            f"                 (ite StartBool Start Start)))\n{GRAMMAR_BOOL}\n\n"
            + "".join(f"(declare-var {p} Int)\n" for p in params) + "\n")


def nested_and(terms):
    return terms[0] if len(terms) == 1 else f"(and {terms[0]} {nested_and(terms[1:])})"


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8").write(text)
    print("wrote", os.path.relpath(path, ROOT))


def max_sygus(n):
    xs = [f"x{i}" for i in range(n)]
    app = f"(max{n} {' '.join(xs)})"
    ors = f"(= {xs[-1]} {app})"
    for x in reversed(xs[:-1]):
        ors = f"(or (= {x} {app})\n            {ors})"
    body = "".join(f"(constraint (>= {app} {x}))\n" for x in xs) + f"(constraint {ors})\n\n(check-synth)\n"
    write(os.path.join(ROOT, "spec_files", "grammar_variants", f"max{n}_sygus.sl"),
          f"; max{n}_sygus.sl — generated by scripts/gen_scaled_specs.py: max_n with the SyGuS-COMP LIA grammar.\n\n"
          + header(f"max{n}", xs) + body)


def above(n):
    xs = [f"x{i}" for i in range(1, n + 1)]
    app = f"(above{n} {' '.join(xs)})"
    body = "".join(f"(constraint (> {app} {x}))\n" for x in xs) + "\n(check-synth)\n"
    write(os.path.join(ROOT, "spec_files", "scaled", f"above{n}.sl"),
          f"; above{n}.sl — generated by scripts/gen_scaled_specs.py: any value strictly greater than all of\n"
          f"; {n} integers (multi-answer; as spec_files/multi_answer/above4.sl). Known solution: max + 1.\n\n"
          + header(f"above{n}", xs) + body)


def array_search(n):
    xs = [f"x{i}" for i in range(1, n + 1)]
    params = xs + ["k"]
    app = f"(findIdx {' '.join(params)})"
    sorted_ = nested_and([f"(< {xs[i]} {xs[i + 1]})" for i in range(n - 1)])
    cons = [f"(constraint (=> {sorted_} (=> (< k {xs[0]}) (= {app} 0))))"]
    for i in range(n - 1):
        cons.append(f"(constraint (=> {sorted_} (=> (and (> k {xs[i]}) (< k {xs[i + 1]})) (= {app} {i + 1}))))")
    cons.append(f"(constraint (=> {sorted_} (=> (> k {xs[-1]}) (= {app} {n}))))")
    write(os.path.join(ROOT, "spec_files", "scaled", f"array_search{n}.sl"),
          f"; array_search{n}.sl — generated by scripts/gen_scaled_specs.py: index at which k fits in a sorted\n"
          f"; {n}-element array ({n + 1}-region case split; as spec_files/case_split/array_search4.sl).\n\n"
          + header("findIdx", params) + "\n".join(cons) + "\n\n(check-synth)\n")


if __name__ == "__main__":
    nmax, nabove, narr = (int(a) for a in (sys.argv[1:4] if len(sys.argv) >= 4 else ("30", "20", "20")))
    max_sygus(nmax)
    above(nabove)
    array_search(narr)
